/** Writes the saved-answer patterns from lib/profile/answer-catalog.ts into extension/page-logic.js (between markers). */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { ANSWER_CATALOG } from "../lib/profile/answer-catalog";

export const START = "  // <answer-rules> generated by scripts/sync-extension-rules.ts; do not edit by hand";
export const END = "  // </answer-rules>";

export function rulesBlock(): string {
  const lines = ANSWER_CATALOG.map((e) => `    { key: ${JSON.stringify(e.key)}, pattern: /${e.match.source}/${e.match.flags} },`);
  return [START, "  var RULES = [", ...lines, "  ];", END].join("\n");
}

export function syncedSource(source: string): string {
  const a = source.indexOf(START);
  const b = source.indexOf(END);
  if (a < 0 || b < 0) throw new Error("answer-rules markers missing in extension/page-logic.js");
  return source.slice(0, a) + rulesBlock() + source.slice(b + END.length);
}

if (process.argv[1] && /sync-extension-rules/.test(process.argv[1])) {
  const file = path.join(process.cwd(), "extension/page-logic.js");
  writeFileSync(file, syncedSource(readFileSync(file, "utf8")));
  console.log(`synced ${ANSWER_CATALOG.length} rules`);
}
